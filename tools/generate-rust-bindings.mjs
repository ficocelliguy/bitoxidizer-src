// Regenerates src/utils/rust/NsBindings.generated.ts: CarciniScript's typed NS bindings for `.rs`
// scripts, generated from NetscriptDefinitions.d.ts. Run after changing the NS API:
//
//   npm run generate:rust-bindings
//
// With --check, only reports whether the committed file is stale (exit code 1 if so).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { dtsToRust } from "carciniscript/dts2rs";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dtsPath = path.join(root, "src/ScriptEditor/NetscriptDefinitions.d.ts");
const outPath = path.join(root, "src/utils/rust/NsBindings.generated.ts");

const rust = dtsToRust(fs.readFileSync(dtsPath, "utf8").replace(/\r\n/g, "\n"));
const generated =
  "// Generated by `npm run generate:rust-bindings` from NetscriptDefinitions.d.ts. Do not edit.\n" +
  "// Typed NS bindings for CarciniScript (Rust declarations; see carciniscript/tools/dts2rs.mjs).\n" +
  `export const nsBindings = ${JSON.stringify(rust)};\n`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== generated) {
    console.error(`${path.relative(root, outPath)} is out of date. Run: npm run generate:rust-bindings`);
    process.exit(1);
  }
} else {
  fs.writeFileSync(outPath, generated);
  console.log(`Wrote ${path.relative(root, outPath)} (${(generated.length / 1024).toFixed(0)} KB)`);
}
